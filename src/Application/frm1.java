            if(cbSafety.isSelected())
            {
                s = true;
            }
            else
            {
                s = false;
            }
            
            if (rbnSunny.isSelected())
            {
                we = "Sunny";
            }
            else if (rbnCloudy.isSelected())
            {
                we = "Cloudy";
            }
            else if (rbnPartlyCloudy.isSelected())
            {
                we = "Partly Cloudy";
            }
            else if (rbnRaining.isSelected())
            {
                we = "Raining";
            }
            else
            {
                we = "Windy";
            }
            
            Log f = new Log(n,date,t,d,ai,ao,w,s,temp,v,we,bn,bnum,c); //New Log object
            lm.insertLog(f); //Log object entered into the array and database
            
                txfDate.setText("");
