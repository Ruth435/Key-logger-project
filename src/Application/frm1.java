    private void btnLogIn1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLogIn1ActionPerformed
        try{
        Scanner scFile = new Scanner (new File ("UsernamesAndPasswords.txt")); //Creates a scanner for the text file
        String username;
        String password;
        boolean correct = false;
       
        while(scFile.hasNext()) //Checks each line in the text file against the users entry
        {
             
            String line = scFile.nextLine();
            Scanner scLine = new Scanner (line).useDelimiter("#");
            username = scLine.next();
            password = scLine.next();
            if(password.equals(txfPassword1.getText()) && username.equals(txfUsername1.getText())) // checks username and password against current line of the text file
            {
                tbpMain.setVisible(true);
                pnlHome.setVisible(true);
                pnlLogIn.setVisible(false);
                correct = true;
            }
            scLine.close();
        }
        scFile.close();
        if (correct == false)
        {
            //Displayes error if incorrect cradentials are entered
           JOptionPane. showMessageDialog(null, "Incorrect Username or password", "", JOptionPane. ERROR_MESSAGE);
        }
        }
        catch(Exception e){
            JOptionPane. showMessageDialog(null, "Error, pleae try again", "", JOptionPane. ERROR_MESSAGE);

        }
    }//GEN-LAST:event_btnLogIn1ActionPerformed

