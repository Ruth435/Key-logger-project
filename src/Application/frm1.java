                    ",   [Weight] = " + w +
                    ",   [Depth] = " + d +
                    ",   [Time] = " + t +
                    ",   [Temp] = " + temp +
                    ",   [Visability] = " + v +
                    ",   [Weather] = '" + we +
                    "',  [NameOfBuddy] = '" + bn +
                    "',  [BuddyCertNumber] = " + bnum +
                    ",   [SafetyStop] = '" + s +
                    "',  [Comments] = '" + c + 
                    "' WHERE DIveNumber =" + n + ";";
