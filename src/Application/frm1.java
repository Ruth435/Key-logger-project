    private void btnSearchEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchEditActionPerformed
       try{ //recives a Dive number, finds the dive number and enters each peice of information into the corresponding field
        ResultSet rs = dbman.queryDatabase("SELECT DISTINCT* FROM tblLog WHERE DiveNumber =" + Integer.parseInt(txfDiveNumEdit.getText()));
                rs.next();
                Date date = rs.getDate("DiveDate");
                LocalDate localDate = date.toLocalDate();
                txfDateEdit.setText(String.valueOf(localDate));
                txfAirInEdit.setText(String.valueOf(rs.getInt("AirIn")));
                txfAirOutEdit.setText(String.valueOf(rs.getInt("AirOut")));
                txfWeightEdit.setText(String.valueOf(rs.getInt("Weight")));
                txfDepthEdit.setText(String.valueOf(rs.getInt("Depth")));
                txfTmeEdit.setText(String.valueOf(rs.getInt("Time")));
                txfTempEdit.setText(String.valueOf(rs.getDouble("Temp")));
                txfVisabilityEdit.setText(String.valueOf(rs.getInt("Visability")));
                boolean safe = rs.getBoolean("SafetyStop");
                cbSafetyEdit.setSelected(safe);
                txfBuddyEdit.setText(rs.getString("NameOfBuddy"));
                txfBuddyNumEdit.setText(String.valueOf(rs.getInt("BuddyCertNumber")));
                txfCommentsEdit.setText(rs.getString("Comments"));
                
            if (rs.getString("Weather").equalsIgnoreCase("Sunny"))
            {
                rbnSunnyEdit.setSelected(true);
            }
            else if (rs.getString("Weather").equalsIgnoreCase("Cloudy"))
            {
                rbnCloudyEdit.setSelected(true);
            }
            else if (rs.getString("Weather").equalsIgnoreCase("Partly Cloudy"))
            {
                rbnPartlyCloudyEdit.setSelected(true);
            }
            else if (rs.getString("Weather").equalsIgnoreCase("Raining"))
            {
                rbnRainingEdit.setSelected(true);
            }
            else
            {
                rbnWindyEdit.setSelected(true);
            }
                }
            catch(SQLException e) //Catches any sql errors that may occur
        {
            JOptionPane. showMessageDialog(null, "Could not find entry", "", JOptionPane. ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSearchEditActionPerformed

