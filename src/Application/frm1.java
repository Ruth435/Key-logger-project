    private void btnDiveSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDiveSearchActionPerformed
        try //Searches for an entry by dive number and returns it to the table if found
        {
            DefaultTableModel dtm = (DefaultTableModel) tblLogs.getModel();
            dtm.setRowCount(0); //Empties the Jtable
            tblLogs.removeAll();
            model = (DefaultTableModel)tblLogs.getModel();
            ResultSet rs = dbman.queryDatabase("SELECT * FROM tblLog WHERE DiveNumber =" + Integer.parseInt(txfDiveSearch.getText())); //Retrives entry(s) from the database

            while(rs.next())
            {
                model.addRow(new Object[]{rs.getInt("DiveNumber"),rs.getDate("DiveDate"),
                    rs.getInt("AirIn"),rs.getInt("AirOut"),rs.getInt("Weight"),rs.getInt("Depth"),rs.getInt("Time"),rs.getDouble("Temp"),rs.getInt("Visability"),rs.getString("Weather"),
                    rs.getString("NameOfBuddy"),rs.getInt("BuddyCertNumber"), rs.getBoolean("SafetyStop"),rs.getString("Comments")});
        }
            txfDiveSearch.setText(""); //Clears the text field
            model.addRow(new Object[]{}); //Adds row to the table
        }
        catch(SQLException e) //Catches any sql Errors
        {
            JOptionPane. showMessageDialog(null, "Entry not found", "", JOptionPane. ERROR_MESSAGE);            
        }
    
    }//GEN-LAST:event_btnDiveSearchActionPerformed

